"""Results routes: aggregated LLM-powered assessment results.

A completed session's result is composed of three intelligent parts:

1. **Narrative service** — a reflective temperament + emotion narrative
   generated by the LLM (`app/services/narrative_service.py`).
2. **Motion service** — a dynamic "trait motion" interpretation of how the
   four temperament tendencies shift across situations
   (`app/services/motion_service.py`).
3. **Recommendation service** — rule-based personalized recommendations
   matched to the session's emotion assessments and temperament scores
   (`app/services/recommendation_service.py`).

Endpoints
---------
POST /api/v1/results/sessions/{session_id}/generate
    Generate (and persist) narrative + motion + recommendations for a
    completed session.
GET /api/v1/results/sessions/{session_id}/stream
    Server-Sent Events stream that streams the narrative and motion text
    token-by-token as the LLM produces them, followed by the full
    recommendation payload and a ``done`` event.
"""

import asyncio
import json
import uuid
from typing import Any, AsyncGenerator

from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import StreamingResponse
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.database import get_db, run_sync
from app.core.llm import get_llm
from app.models import (
    AssessmentSession,
    TemperamentScore,
    AssessmentReport,
    EmotionAssessment,
)
from app.services.narrative_service import generate_narrative_report, NARRATIVE_SYSTEM_PROMPT
from app.services.motion_service import generate_motion_interpretation, MOTION_SYSTEM_PROMPT
from app.services.recommendation_service import (
    match_and_generate_recommendations,
    seed_recommendation_templates,
)
from app.models.recommendation import Recommendation, RecommendationTemplate

router = APIRouter()


def _session_score_rows(db: Session, session_id: uuid.UUID) -> list[dict[str, Any]]:
    rows = db.scalars(
        select(TemperamentScore).where(TemperamentScore.session_id == session_id)
    ).all()
    return [
        {
            "dimension": r.dimension,
            "score": float(r.score) if r.score is not None else None,
            "normalized_score": float(r.score) if r.score is not None else None,
            "n_items": r.n_items,
            "n_areas": r.n_areas,
            "interpretation": "",
        }
        for r in rows
    ]


def _emotion_rows(db: Session, session_id: uuid.UUID) -> list[dict[str, Any]]:
    rows = db.scalars(
        select(EmotionAssessment).where(EmotionAssessment.session_id == session_id)
    ).all()
    return [
        {
            "emotion": row.emotion,
            "frequency": row.frequency,
            "intensity": row.intensity,
            "duration": row.duration,
            "impact": row.impact,
            "burden_index": float(row.burden_index),
            "band": row.band.value if hasattr(row.band, "value") else str(row.band),
        }
        for row in rows
    ]


def _dominant(scores: list[dict[str, Any]]) -> str:
    leaders = sorted(
        scores,
        key=lambda x: x.get("normalized_score") or x.get("score") or 0,
        reverse=True,
    )
    if leaders:
        return str(leaders[0]["dimension"]).capitalize()
    return "Unknown"


@router.post("/sessions/{session_id}/generate")
async def generate_result(session_id: uuid.UUID, db: Session = Depends(get_db)):
    """Generate and persist narrative + motion + recommendations for a session."""
    def _generate() -> dict[str, Any]:
        session = db.get(AssessmentSession, session_id)
        if not session:
            raise HTTPException(404, "Session not found")
        if session.status != "completed":
            raise HTTPException(409, "Assessment is not completed yet")

        scores = _session_score_rows(db, session_id)
        emotion_payload = _emotion_rows(db, session_id)

        narrative_payload = generate_narrative_report(
            scores=scores,
            user_id=str(session.user_id),
            emotion_rows=emotion_payload,
        )
        motion_payload = generate_motion_interpretation(
            scores=scores,
            user_id=str(session.user_id),
            emotion_rows=emotion_payload,
        )

        # Persist narrative + motion together in the report snapshot (one report
        # per session; locate by session_id since the PK is ``id``).
        report = db.scalar(
            select(AssessmentReport).where(AssessmentReport.session_id == session_id)
        )
        narrative_snapshot = {
            **narrative_payload,
            "motion": motion_payload.get("motion"),
            "motion_prompt_version": motion_payload.get("prompt_version"),
            "motion_llm_model": motion_payload.get("llm_model"),
        }
        if report is None:
            report = AssessmentReport(
                session_id=session_id,
                structured={
                    "temperament_scores": scores,
                    "emotion_assessments": emotion_payload,
                },
                narrative=narrative_snapshot,
                llm_model=narrative_payload.get("llm_model"),
                prompt_version=narrative_payload.get("prompt_version"),
            )
            db.add(report)
        else:
            report.structured = {
                "temperament_scores": scores,
                "emotion_assessments": emotion_payload,
            }
            report.narrative = narrative_snapshot
            report.llm_model = narrative_payload.get("llm_model")
            report.prompt_version = narrative_payload.get("prompt_version")
        db.flush()

        # Recommendations from the knowledge-pack rule engine.
        seed_recommendation_templates(db)
        recs = match_and_generate_recommendations(db, session_id)
        templates_by_id = {
            str(t.id): t for t in db.scalars(select(RecommendationTemplate)).all()
        }
        db.commit()

        recommendation_payload = [
            {
                "id": str(r.id),
                "template_id": r.template_id,
                "title": (templates_by_id.get(r.template_id).title
                          if templates_by_id.get(r.template_id) else r.template_id),
                "body": (
                    templates_by_id.get(r.template_id).body
                    if templates_by_id.get(r.template_id)
                    else {}
                ),
                "status": r.status.value,
                "rationale": r.rationale,
            }
            for r in recs
        ]

        return {
            "session_id": session_id,
            "report_id": str(report.id),
            "status": "completed",
            "dominant": _dominant(scores),
            "temperament_scores": scores,
            "emotion_assessments": emotion_payload,
            "narrative": narrative_payload.get("narrative", ""),
            "motion": motion_payload.get("motion", ""),
            "narrative_report": narrative_payload,
            "motion_report": motion_payload,
            "recommendations": recommendation_payload,
            "llm_model": narrative_payload.get("llm_model"),
            "prompt_version": narrative_payload.get("prompt_version"),
            "disclaimer": (
                "Classical temperaments and trait-motion readings are reflective frameworks, "
                "not validated diagnoses. Scores are self-reported tendencies."
            ),
        }

    return await run_sync(_generate)


async def _result_event_stream(
    session_id: uuid.UUID, db: Session
) -> AsyncGenerator[str, None]:
    """SSE stream: narrative tokens, motion tokens, recommendations, done."""
    session = db.get(AssessmentSession, session_id)
    if not session:
        yield (
            f"event: error\ndata: {json.dumps({'message': 'Session not found'})}\n\n"
        )
        yield f"event: done\ndata: {json.dumps({'status': 'failed'})}\n\n"
        return
    if session.status != "completed":
        yield (
            f"event: error\ndata: {json.dumps({'message': 'Assessment is not completed yet'})}\n\n"
        )
        yield f"event: done\ndata: {json.dumps({'status': 'failed'})}\n\n"
        return

    scores = _session_score_rows(db, session_id)
    emotion_payload = _emotion_rows(db, session_id)
    user_id = str(session.user_id)
    llm = get_llm()

    # --- Stream narrative tokens (LLM) ---
    narrative_ctx = (
        "User Scores:\n"
        + "\n".join(
            f"- {s.get('dimension')}: {s.get('normalized_score') or s.get('score')}/100"
            for s in scores
        )
        + "\n\nEmotion Self-Reports:\n"
        + (chr(10).join(
            f"- {e.get('emotion')}: intensity={e.get('intensity')}/10, band={e.get('band')}"
            for e in emotion_payload
        )
        if emotion_payload
        else "No emotion self-reports were submitted.")
        + "\n\nPlease generate a 2-3 paragraph reflective summary that explains the temperament pattern and how the reported emotions may reinforce or soften those tendencies."
    )

    async for delta in llm.stream_generate(prompt=narrative_ctx, system=NARRATIVE_SYSTEM_PROMPT, max_tokens=600):
        yield f"event: narrative\ndata: {json.dumps({'delta': delta, 'session_id': str(session_id)})}\n\n"
        await asyncio.sleep(0)

    # --- Stream motion tokens (LLM) ---
    motion_ctx = (
        "User Scores:\n"
        + "\n".join(
            f"- {s.get('dimension')}: {s.get('normalized_score') or s.get('score')}/100"
            for s in scores
        )
        + "\n\nEmotion Self-Reports:\n"
        + (chr(10).join(
            f"- {e.get('emotion')}: intensity={e.get('intensity')}/10, band={e.get('band')}"
            for e in emotion_payload
        )
        if emotion_payload
        else "No emotion self-reports were submitted.")
        + "\n\nDescribe how these temperament tendencies move and interact across different situations — social settings, focused work, stress, and rest — and which combinations tend to dominate when. Keep it grounded in the scores above."
    )

    async for delta in llm.stream_generate(prompt=motion_ctx, system=MOTION_SYSTEM_PROMPT, max_tokens=600):
        yield f"event: motion\ndata: {json.dumps({'delta': delta, 'session_id': str(session_id)})}\n\n"
        await asyncio.sleep(0)

    # --- Recommendations (rule engine, delivered whole) ---
    seed_recommendation_templates(db)
    recs = match_and_generate_recommendations(db, session_id)
    recommendation_payload = [
        {
            "id": str(r.id),
            "template_id": r.template_id,
            "title": (db.get(RecommendationTemplate, r.template_id) or {}).title
            if db.get(RecommendationTemplate, r.template_id)
            else r.template_id,
            "body": (
                (db.get(RecommendationTemplate, r.template_id) or {}).body
                if db.get(RecommendationTemplate, r.template_id)
                else {}
            ),
            "status": r.status.value,
            "rationale": r.rationale,
        }
        for r in recs
    ]
    yield f"event: recommendations\ndata: {json.dumps({'recommendations': recommendation_payload, 'session_id': str(session_id)})}\n\n"
    yield f"event: done\ndata: {json.dumps({'session_id': str(session_id), 'status': 'completed'})}\n\n"


@router.get("/sessions/{session_id}/stream")
async def stream_result(session_id: uuid.UUID, db: Session = Depends(get_db)):
    """Server-Sent Events stream of the LLM-generated result for a session.

    Event stream shape::

        event: narrative
        data: {"delta": "...", "session_id": "..."}

        event: motion
        data: {"delta": "...", "session_id": "..."}

        event: recommendations
        data: {"recommendations": [...], "session_id": "..."}

        event: done
        data: {"session_id": "...", "status": "completed"}
    """
    return StreamingResponse(
        _result_event_stream(session_id, db),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache, no-transform",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",  # disable buffering behind nginx
        },
    )
